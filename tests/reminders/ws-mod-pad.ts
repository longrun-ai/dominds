function getPadText(reminder: unknown): string {
  if (typeof reminder !== 'object' || reminder === null || Array.isArray(reminder)) {
    throw new Error('Reminder must be an object');
  }
  const meta = (reminder as { meta?: unknown }).meta;
  if (typeof meta !== 'object' || meta === null || Array.isArray(meta)) {
    throw new Error('Reminder meta must be an object');
  }
  const text = (meta as { text?: unknown }).text;
  if (typeof text !== 'string') {
    throw new Error('Reminder meta.text must be a string');
  }
  return text;
}

function getPadId(reminder: unknown): string | undefined {
  if (typeof reminder !== 'object' || reminder === null || Array.isArray(reminder)) {
    return undefined;
  }
  const meta = (reminder as { meta?: unknown }).meta;
  if (typeof meta !== 'object' || meta === null || Array.isArray(meta)) {
    return undefined;
  }
  const record = meta as Record<string, unknown>;
  return record['kind'] === 'ws_mod_pad' && typeof record['padId'] === 'string'
    ? record['padId']
    : undefined;
}

function requirePadReminder(dlg: MainDialog, padId: string): MainDialog['reminders'][number] {
  const reminder = dlg.reminders.find((candidate) => getPadId(candidate) === padId);
  assert.ok(reminder, `Expected pad reminder to exist: ${padId}`);
  return reminder;
}

function hasPadReminder(dlg: MainDialog, padId: string): boolean {
  return dlg.reminders.some((candidate) => getPadId(candidate) === padId);
}

const evidence = semanticEvidenceCollector('dominds-pad-lifecycle-');
async function main(): Promise<void> {
  await withTempRtws(async (tmpRoot) => {
    for (const language of ['en', 'zh'] as const) {
      setWorkLanguage(language);
      const dlg = await createMainDialog('tester');
      const caller = new Team.Member({
        id: 'tester',
        name: 'Tester',
        read_dirs: ['**'],
        write_dirs: ['**'],
      });
      const secret = 'SECRET_BODY_FOR_WS_MOD_PAD_TEST';

      const emptyModeWriteArgs = validateArgs(padWriteTool.parameters, {
        pad_id: 'draft1',
        content: secret,
        mode: '',
      });
      assert.equal(
        emptyModeWriteArgs.ok,
        true,
        'pad_write should accept empty-string default mode',
      );

      const emptyModeLoadArgs = validateArgs(padLoadFileRangeTool.parameters, {
        pad_id: 'draft1',
        path: 'main/tool.ts',
        range: '1~1',
        mode: '',
      });
      assert.equal(
        emptyModeLoadArgs.ok,
        true,
        'pad_load_file_range should accept empty-string default mode',
      );
      const fullFileLoadArgs = validateArgs(padLoadFileRangeTool.parameters, {
        pad_id: 'whole_file',
        path: 'whole.txt',
      });
      assert.equal(
        fullFileLoadArgs.ok,
        true,
        'pad_load_file_range should allow omitted range for full-file load',
      );

      const missingIntentOutput = (
        await padWriteTool.call(dlg, caller, {
          pad_id: 'missing_intent',
          content: 'temporary body\n',
          mode: '',
        })
      ).content;
      assert.ok(toolOutputData(missingIntentOutput).status === 'ok');
      assert.ok(
        toolOutputData(missingIntentOutput).notice === 'PAD_INTENT_MISSING',
        'pad_write should report a successful notice when intent metadata is missing',
      );
      const missingIntentDisplay = requirePadReminder(dlg, 'missing_intent').content;
      await padDeleteTool.call(dlg, caller, { pad_id: 'missing_intent' });
      assert.equal(dlg.reminders.length, 0, 'missing-intent setup pad should be cleaned up');

      const writeOutput = (
        await padWriteTool.call(dlg, caller, {
          pad_id: 'draft1',
          content: `${secret}\nline2\n`,
          mode: '',
          intent: 'Test pad display with line-numbered body and task intent.',
          completion: 'Delete after ws_mod pad reminder contract assertions finish.',
          source_note: 'Generated by reminder contract test.',
        })
      ).content;
      assert.ok(toolOutputData(writeOutput).status === 'ok');
      assert.ok(!writeOutput.includes(secret), 'pad_write result must not echo pad body');
      assert.equal(toolOutputData(writeOutput).notice, undefined);
      const reminder = requirePadReminder(dlg, 'draft1');
      assert.equal(serializeReminderContentMeta(reminder), undefined);
      assert.ok(reminder.content.includes(secret), 'the supplied body reaches its UI display');
      const displayAtWrite = reminder.content;
      const inputMeta = reminder.meta;
      assert.ok(inputMeta !== null && typeof inputMeta === 'object' && !Array.isArray(inputMeta));
      assert.equal(inputMeta.intent, 'Test pad display with line-numbered body and task intent.');
      assert.equal(
        inputMeta.completion,
        'Delete after ws_mod pad reminder contract assertions finish.',
      );
      assert.equal(inputMeta.sourceNote, 'Generated by reminder contract test.');
      const rendered = await wsModPadReminderOwner.renderReminder(dlg, reminder);
      assert.ok(rendered.type === 'environment_msg');
      assert.equal(rendered.role, 'user');
      assert.ok(rendered.content.includes(secret));
      const maintenanceReference = formatReminderMaintenanceReference(language, [
        { id: reminder.id, meta: serializeReminderMaintenanceMeta(reminder) },
      ]);
      assert.ok(maintenanceReference);
      assert.equal(maintenanceReference.includes(secret), false);
      const manualDelete = await deleteReminderTool.call(dlg, caller, { reminder_id: reminder.id });
      assert.equal(manualDelete.outcome, 'failure');
      const manualDeleteOutput = manualDelete.content;
      assert.equal(getPadText(requirePadReminder(dlg, 'draft1')), `${secret}\nline2\n`);

      const editOutput = (
        await padEditTool.call(dlg, caller, {
          pad_id: 'draft1',
          range: '2~2',
          content: 'changed\n',
        })
      ).content;
      assert.ok(toolOutputData(editOutput).status === 'ok');
      assert.ok(!editOutput.includes('changed'), 'pad_edit result must not echo edited body');
      assert.equal(getPadText(requirePadReminder(dlg, 'draft1')), `${secret}\nchanged\n`);
      assert.ok(requirePadReminder(dlg, 'draft1').content.includes('changed'));

      const insertOutput = (
        await padInsertTool.call(dlg, caller, {
          pad_id: 'draft1',
          line: 2,
          content: 'INSERTED_BODY_TOKEN\n',
        })
      ).content;
      assert.ok(toolOutputData(insertOutput).status === 'ok');
      assert.ok(
        !insertOutput.includes('INSERTED_BODY_TOKEN'),
        'pad_insert result must not echo inserted body',
      );
      assert.equal(
        getPadText(requirePadReminder(dlg, 'draft1')),
        `${secret}\nINSERTED_BODY_TOKEN\nchanged\n`,
      );
      assert.ok(requirePadReminder(dlg, 'draft1').content.includes('INSERTED_BODY_TOKEN'));
      const displayAfterInsert = requirePadReminder(dlg, 'draft1').content;

      const copyOutput = (
        await padCopyTool.call(dlg, caller, {
          from_pad_id: 'draft1',
          from_range: '1~1',
          to_pad_id: 'draft2',
        })
      ).content;
      assert.ok(toolOutputData(copyOutput).status === 'ok');
      assert.ok(!copyOutput.includes(secret), 'pad_copy result must not echo copied body');
      assert.equal(getPadText(requirePadReminder(dlg, 'draft2')), `${secret}\n`);
      const copiedMeta = requirePadReminder(dlg, 'draft2').meta;
      assert.ok(
        copiedMeta !== null && typeof copiedMeta === 'object' && !Array.isArray(copiedMeta),
      );
      assert.equal(copiedMeta.intent, inputMeta.intent);

      const moveOutput = (
        await padMoveTool.call(dlg, caller, {
          from_pad_id: 'draft1',
          from_range: '3~3',
          to_pad_id: 'draft2',
          to_range: '2~',
        })
      ).content;
      assert.ok(toolOutputData(moveOutput).status === 'ok');
      assert.ok(!moveOutput.includes('changed'), 'pad_move result must not echo moved body');
      assert.equal(
        getPadText(requirePadReminder(dlg, 'draft1')),
        `${secret}\nINSERTED_BODY_TOKEN\n`,
      );
      assert.equal(getPadText(requirePadReminder(dlg, 'draft2')), `${secret}\nchanged\n`);

      const deleteRangeOutput = (
        await padDeleteRangeTool.call(dlg, caller, {
          pad_id: 'draft2',
          range: '1~1',
        })
      ).content;
      assert.ok(toolOutputData(deleteRangeOutput).status === 'ok');
      assert.ok(
        !deleteRangeOutput.includes(secret),
        'pad_delete_range result must not echo remaining body',
      );
      assert.equal(getPadText(requirePadReminder(dlg, 'draft2')), 'changed\n');

      const fullFileToken = 'FULL_FILE_LOAD_TOKEN';
      await fs.writeFile(
        path.join(tmpRoot, 'whole.txt'),
        `alpha\n${fullFileToken}\nomega\n`,
        'utf8',
      );
      const fullFileLoadOutput = (
        await padLoadFileRangeTool.call(dlg, caller, {
          pad_id: 'whole_file',
          path: 'whole.txt',
          mode: 'create',
        })
      ).content;
      assert.ok(toolOutputData(fullFileLoadOutput).status === 'ok');
      assert.ok(
        !fullFileLoadOutput.includes(fullFileToken),
        'pad_load_file_range full-file result must not echo file body',
      );
      assert.equal(
        getPadText(requirePadReminder(dlg, 'whole_file')),
        `alpha\n${fullFileToken}\nomega\n`,
      );
      await padDeleteTool.call(dlg, caller, { pad_id: 'whole_file' });

      await fs.writeFile(path.join(tmpRoot, 'target.txt'), 'old1\nold2\n', 'utf8');
      const padRangeEditOutput = (
        await fileRangeEditTool.call(dlg, caller, {
          pad_id: 'draft2',
          pad_range: '1~1',
          path: 'target.txt',
          range: '2~2',
        })
      ).content;
      assert.ok(toolOutputData(padRangeEditOutput).mode === 'file_range_edit');
      assert.ok(toolOutputData(padRangeEditOutput).source === 'pad');
      const editMetadata = toolOutputData(padRangeEditOutput);
      assert.equal(editMetadata.pad_intent, inputMeta.intent);
      assert.equal(editMetadata.pad_completion, inputMeta.completion);
      assert.equal(editMetadata.pad_delete_when_done, true);
      assert.ok(
        !padRangeEditOutput.includes('changed'),
        'pad-sourced file_range_edit result must not echo selected pad body',
      );
      assert.equal(await fs.readFile(path.join(tmpRoot, 'target.txt'), 'utf8'), 'old1\nchanged\n');

      const previewRangeEditOutput = (
        await fileRangeEditTool.call(dlg, caller, {
          pad_id: 'draft2',
          pad_range: '1~1',
          path: 'target.txt',
          range: '1~1',
          preview: true,
        })
      ).content;
      assert.equal(toolOutputData(previewRangeEditOutput).preview, true);
      assert.equal(await fs.readFile(path.join(tmpRoot, 'target.txt'), 'utf8'), 'old1\nchanged\n');
      assert.equal(getPadText(requirePadReminder(dlg, 'draft2')), 'changed\n');

      const createFromPadOutput = (
        await createNewFileTool.call(dlg, caller, {
          pad_id: 'draft2',
          pad_range: '1~1',
          path: `created-from-pad-${language}.txt`,
        })
      ).content;
      assert.ok(toolOutputData(createFromPadOutput).mode === 'create_new_file');
      assert.ok(toolOutputData(createFromPadOutput).source === 'pad');
      assert.equal(toolOutputData(createFromPadOutput).pad_intent, inputMeta.intent);
      assert.equal(
        await fs.readFile(path.join(tmpRoot, `created-from-pad-${language}.txt`), 'utf8'),
        'changed\n',
      );

      await fs.writeFile(path.join(tmpRoot, 'target-append.txt'), 'head1\nhead2\n', 'utf8');
      const appendRangeEditOutput = (
        await fileRangeEditTool.call(dlg, caller, {
          pad_id: 'draft2',
          pad_range: '1~1',
          path: 'target-append.txt',
          range: '3~',
        })
      ).content;
      assert.ok(toolOutputData(appendRangeEditOutput).mode === 'file_range_edit');
      assert.ok(
        !appendRangeEditOutput.includes('changed'),
        'pad-sourced file_range_edit append result must not echo selected pad body',
      );
      assert.equal(
        await fs.readFile(path.join(tmpRoot, 'target-append.txt'), 'utf8'),
        'head1\nhead2\nchanged\n',
      );

      await padDeleteTool.call(dlg, caller, { pad_id: 'draft2' });
      const deleteOutput = (await padDeleteTool.call(dlg, caller, { pad_id: 'draft1' })).content;
      assert.ok(toolOutputData(deleteOutput).status === 'ok');
      assert.equal(hasPadReminder(dlg, 'draft1'), false, 'pad_delete should remove draft1');
      assert.equal(hasPadReminder(dlg, 'draft2'), false, 'pad_delete should remove draft2');

      dlg.reminders.push(
        materializeReminder({
          id: 'pad_broken1',
          content: 'broken pad',
          owner: wsModPadReminderOwner,
          meta: { kind: 'ws_mod_pad' },
          scope: 'dialog',
          renderMode: 'markdown',
        }),
      );
      assert.ok(dlg.reminders.some((item) => item.id === 'pad_broken1'));
      const brokenDeleteOutput = (await padDeleteTool.call(dlg, caller, { pad_id: 'broken1' }))
        .content;
      assert.ok(toolOutputData(brokenDeleteOutput).status === 'ok');
      assert.equal(
        dlg.reminders.some((item) => item.id === 'pad_broken1'),
        false,
        'pad_delete should clean unreadable pad metadata by id',
      );

      evidence.record({
        id: `missing-${language}`,
        scenario:
          'An owner creates a temporary pad without intent metadata, then explicitly deletes it.',
        businessValue:
          'Make missing task purpose visible without claiming the write failed or creating a new human request.',
        context: {
          language,
          writeSucceeded: true,
          padWasPresent: true,
          explicitDeletionSucceeded: true,
        },
        reviewQuestions: [
          'Does the actual notice/display accurately distinguish absent purpose metadata from a failed operation and keep pad content as task data?',
        ],
        actualText: JSON.stringify(
          { result: missingIntentOutput, display: missingIntentDisplay },
          null,
          2,
        ),
      });
      evidence.record({
        id: `projection-${language}`,
        scenario:
          'A pad has supplied body, intent and completion metadata; the runtime displays/projects it, blocks generic reminder deletion, and updates the display after actual edit and insert.',
        businessValue:
          'Preserve useful data and line references while keeping human-supplied pad content distinct from runtime maintenance instructions.',
        context: {
          language,
          initialPadBody: `${secret}\nline2\n`,
          updatedPadBody: `${secret}\nINSERTED_BODY_TOKEN\nchanged\n`,
          genericDeletionRefused: true,
          scope:
            'Direct dialog/reminder projection and control APIs, not provider compliance or browser rendering.',
        },
        reviewQuestions: [
          'Do the actual UI and user-role projections keep body/purpose/completion and line references accurate at their observed stages?',
          'Are pad body data and assistant-side maintenance guidance clearly separated, with actionable tools for the managed pad?',
        ],
        actualText: JSON.stringify(
          {
            initialDisplay: displayAtWrite,
            projected: rendered,
            updatedDisplay: displayAfterInsert,
            maintenanceReference,
            blockedDeletion: manualDeleteOutput,
          },
          null,
          2,
        ),
      });
      evidence.record({
        id: `cleanup-${language}`,
        scenario:
          'Actual file edits use a pad and propagate its supplied metadata; a different-byte preview preserves file and pad, actual creation follows, and malformed pad metadata can be deleted by reminder identity.',
        businessValue:
          'Keep temporary source data until the real completion condition is met and allow explicit cleanup without erasing the effect of the completed file edit.',
        context: {
          language,
          padBody: 'changed\n',
          previewOriginalFile: 'old1\nchanged\n',
          previewRange: '1~1',
          previewFileUnchanged: true,
          padUnchangedAfterPreview: true,
          completionCondition: 'Delete after ws_mod pad reminder contract assertions finish.',
          malformedReminderIdentityRemoved: true,
        },
        reviewQuestions: [
          'Does actual post-write cleanup guidance remain conditional on the supplied completion condition?',
          'Does preview guidance preserve the pad until real writing or abandonment, without pretending the preview already wrote?',
          'Are success and malformed-pad cleanup summaries consistent with actual observed effects?',
        ],
        actualText: JSON.stringify(
          {
            actualEdit: padRangeEditOutput,
            preview: previewRangeEditOutput,
            creation: createFromPadOutput,
            malformedCleanup: brokenDeleteOutput,
          },
          null,
          2,
        ),
      });
      console.log('✓ ws_mod pad reminder contract test passed');
    }
  });
  await evidence.write();
}

void main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
